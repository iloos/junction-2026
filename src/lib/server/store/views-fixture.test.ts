/**
 * Writes fixtures/views/*.json from real tool outputs (FulfilmentView, LineView.physical/unitPrice/comparisonPrice),
 * so UI and agent lanes build against what the server returns. Run with WRITE_VIEW_FIXTURES=1 to regenerate.
 */
import { describe, expect, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { SCOPES_BY_ACTOR, type Plan } from '$lib/core/contracts';
import { createHandlers } from '$lib/core/services/handlers';
import { createDbPorts } from './db-ports';

const chef = {
	workspaceId: 'ws-demo',
	runId: 'run-1',
	actor: { kind: 'chef' as const, id: 'chef-1' },
	scopes: SCOPES_BY_ACTOR.chef,
	via: 'test'
};
const must = <T>(
	r: { ok: true; value: T } | { ok: false; error: { code: string; message: string } }
): T => {
	if (!r.ok) throw new Error(`${r.error.code}: ${r.error.message}`);
	return r.value;
};
const write = (name: string, plan: Plan) => {
	if (!process.env.WRITE_VIEW_FIXTURES) return;
	const slim = {
		$note:
			'Generated by src/lib/server/store/views-fixture.test.ts from real tool outputs (PGlite, fixture catalogue). Shape: Plan with view (PlanView) and lines[].view (LineView).',
		...plan
	};
	writeFileSync(`fixtures/views/${name}.json`, JSON.stringify(slim, null, '\t') + '\n');
};

describe('view fixtures', () => {
	it('christmas plan after the three rescues', async () => {
		const env = await createDbPorts();
		env.overlay.clear();
		const h = createHandlers(env.ports);
		let plan = must(
			await h.plan_event(chef, { kitchenId: 'k-hotel', eventId: 'event-xmas-140' })
		).plan;
		for (const id of ['462490', '462482', '473317']) {
			const line = plan.lines.find((l) => l.productId === id)!;
			plan = must(
				await h.find_substitutes(chef, { planId: plan.id, version: plan.version, lineId: line.id })
			).plan;
		}
		plan = must(await h.get_plan(chef, { planId: plan.id })).plan;
		write('christmas-rescued', plan);
		const f = new Map(plan.view!.fulfilment.map((x) => [x.needId, x]));
		expect(plan.view!.fulfilment.length).toBe(plan.needs.length);
		for (const x of plan.view!.fulfilment) {
			const sum =
				x.supplierConfirmed.value +
				x.awaitingSupplier.value +
				x.plannedKnown.value +
				x.plannedUnknown.value +
				x.unresolved.value;
			expect(Math.abs(sum - x.required.value)).toBeLessThan(0.01);
		}
		writeFileSync(
			'scratch/fulfilment.txt',
			plan
				.view!.fulfilment.map(
					(x) =>
						`${x.label} | req ${x.required.value}${x.required.unit} | known ${x.plannedKnown.value} unk ${x.plannedUnknown.value} unres ${x.unresolved.value} excess ${x.excess.value} | ${x.status}`
				)
				.join('\n') +
				'\n\n' +
				plan.lines
					.map(
						(l) =>
							`${l.productId} ${l.qty.value}${l.qty.unit} ${l.state} phys=${JSON.stringify(l.view?.physical)} unit=${JSON.stringify(l.view?.unitPrice)} cmp=${JSON.stringify(l.view?.comparisonPrice)}`
					)
					.join('\n') +
				`\n\n${JSON.stringify({ asOf: plan.view!.asOf, validUntil: plan.view!.validUntil, mv: plan.view!.mandateVersion })}`
		);
		expect(f.size).toBeGreaterThan(0);
	});
});
