/** F10: a physical amount ("1 l milk") is the demand: sized by the server, kept as a direct need, substitutes sized to it. */
import { beforeEach, describe, expect, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { SCOPES_BY_ACTOR } from '$lib/core/contracts';
import type { CallContext, ToolHandlers } from '$lib/core/ports';
import { createHandlers } from '$lib/core/services/handlers';
import { contentPerSalesUnit } from '$lib/core/demand/sizing';
import * as schema from '../db/schema';
import { createDbPorts } from './db-ports';

const ctx = (kind: keyof typeof SCOPES_BY_ACTOR): CallContext => ({
	workspaceId: 'ws-demo',
	runId: 'run-1',
	actor: { kind, id: `${kind}-1` },
	scopes: SCOPES_BY_ACTOR[kind],
	via: 'test'
});
const must = <T>(
	r: { ok: true; value: T } | { ok: false; error: { code: string; message: string } }
): T => {
	if (!r.ok) throw new Error(`${r.error.code}: ${r.error.message}`);
	return r.value;
};
const MILK = '464201'; // Valio lactose-free milk 1 l, ST

let h: ToolHandlers;
let env: Awaited<ReturnType<typeof createDbPorts>>;
beforeEach(async () => {
	env = await createDbPorts();
	env.overlay.clear();
	h = createHandlers(env.ports);
});

const order = (qty: number, key: string) =>
	h.place_order(ctx('kitchen_agent'), {
		kitchenId: 'k-hotel',
		deliverBy: '2026-12-10',
		idempotencyKey: key,
		lines: [{ productId: MILK, qty, unit: 'ST', amount: { value: 10, unit: 'l' } }]
	});

describe('direct needs', () => {
	it('sizes the amount itself and refuses a qty that disagrees, naming the computed one', async () => {
		const bad = await order(3, 'milk-bad');
		expect(bad.ok ? null : bad.error).toMatchObject({
			code: 'INVALID_INPUT',
			detail: { computedQty: 10, unit: 'ST' }
		});
		const { plan } = must(await order(10, 'milk-ok'));
		expect(plan.needs).toEqual([
			expect.objectContaining({ kind: 'direct', amount: { value: 10, unit: 'l' } })
		]);
		expect(plan.lines[0]).toMatchObject({
			needId: plan.needs[0].id,
			qty: { value: 10, unit: 'ST' }
		});
		expect(plan.view!.fulfilment[0]).toMatchObject({
			required: { value: 10, unit: 'l' },
			plannedKnown: { value: 10 },
			unresolved: { value: 0 }
		});
		expect(plan.lines[0].view).toMatchObject({
			physical: { value: 10, unit: 'l' },
			unitPrice: { per: 'ST' },
			comparisonPrice: { per: 'l' }
		});
		if (process.env.WRITE_VIEW_FIXTURES)
			writeFileSync(
				'fixtures/views/milk-direct.json',
				JSON.stringify(
					{
						$note:
							'Generated by src/lib/server/store/direct.test.ts: place_order 10 l lactose-free milk (amount → direct need), the plan with view and lines[].view.',
						...plan
					},
					null,
					'\t'
				) + '\n'
			);
	});

	it('sizes every substitute to the litres asked for, not to the sales-unit count', async () => {
		const { plan } = must(await order(10, 'milk-sub'));
		env.overlay.setAvailability({ productId: MILK, amount: 0, label: 'simulated: out' });
		const r = must(
			await h.find_substitutes(ctx('chef'), {
				planId: plan.id,
				version: plan.version,
				lineId: plan.lines[0].id,
				apply: false
			})
		);
		const products = await env.ports.catalog.get(r.candidates.map((c) => c.productId));
		const sized = r.candidates.filter((c) => c.rank !== null);
		expect(sized.length).toBeGreaterThan(0);
		for (const l of r.chosen) {
			const litres = contentPerSalesUnit(products.get(l.productId)!, 'l')!;
			expect(l.qty.value * litres).toBeGreaterThanOrEqual(10 - 1e-9);
		}
	});

	it('ops written for an agent run name who started it (initiatedBy)', async () => {
		const run: CallContext = {
			...ctx('kitchen_agent'),
			initiatedBy: { kind: 'chef', id: 'chef-7' }
		};
		must(
			await h.place_order(run, {
				kitchenId: 'k-hotel',
				deliverBy: '2026-12-10',
				idempotencyKey: 'initiated',
				lines: [{ productId: MILK, qty: 1, unit: 'ST' }]
			})
		);
		const ops = await env.db.select().from(schema.ops);
		expect(ops.length).toBeGreaterThan(0);
		for (const o of ops)
			expect((o.envelope as { initiatedBy?: unknown }).initiatedBy).toEqual({
				kind: 'chef',
				id: 'chef-7'
			});
	});
});
